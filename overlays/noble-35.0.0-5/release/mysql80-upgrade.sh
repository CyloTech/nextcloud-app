#!/usr/bin/env bash
# Usage (on the build host): mysql80-upgrade.sh <work dir> <phase> [<image>]
#
# Tests the update of an installation whose database still runs MySQL 8.0,
# as on Appbox instances set up with 31.0.4-2 (Ubuntu's MySQL 8.0) whose
# owners then updated Nextcloud to 35 with the web updater. Nextcloud 31
# created its database user with mysql_native_password, which MySQL 8.4 does
# not load by default. The work directory and container are the ones
# release/recreate-regression.sh creates; run its install phase with the
# 31.0.4-2 image first.
#
# Phases, in this order:
#   nc-upgrade        upgrades the running Nextcloud in place through
#                     $nc_path (published zips, SHA-256 checked) as the web
#                     updater does, adds a test file and records the result
#                     as the new baseline
#   kill              stops the container with SIGKILL, so MySQL 8.0 does not
#                     shut down cleanly (optional, before the recreate)
#   (recreate-regression.sh <work dir> recreate <new image>)
#   check-84 <image>  after the update: MySQL 8.4 runs on the upgraded data,
#                     the 8.0 copy exists, the Nextcloud database user still
#                     uses mysql_native_password and works, the PHP version,
#                     database version, file locking and memcache setup
#                     checks pass, Redis runs, and the test file is in the
#                     file cache
#   rollback <image>  removes the Redis entries from config.php, stops the
#                     container, puts the MySQL 8.0 copy back and recreates
#                     the container from <image> (31.0.4-2); MySQL 8.0 must
#                     run, Nextcloud must work and the test file must be there
#
# Exit status: 0 passed, 1 failed. Only test credentials generated by
# recreate-regression.sh are used.
set -euo pipefail

nc_path="31.0.14 32.0.15 33.0.10 34.0.5 35.0.2"
nc_final=35.0.2

usage() {
    echo "usage: $0 <work dir> nc-upgrade|kill | $0 <work dir> check-84|rollback <image>" >&2
    exit 1
}

[ "$#" -ge 2 ] || usage
work=$1
phase=$2
image=${3:-}
case "$phase" in
    nc-upgrade|kill) ;;
    check-84|rollback) [ -n "$image" ] || usage ;;
    *) usage ;;
esac
case "$work" in
    /dev/shm/nextcloud-recreate.??????) ;;
    *) echo "work directory must be a recreate-regression.sh work directory" >&2; exit 1 ;;
esac
[ -f "$work/name" ] || { echo "no container recorded in $work" >&2; exit 1; }
name=$(cat "$work/name")
admin_user=$(cat "$work/admin_user")
vol=$work/vol
recreate_test=$(cd "$(dirname "$0")" && pwd)/recreate-regression.sh

fail() {
    echo "FAIL: $*" >&2
    exit 1
}

say() {
    echo "[mysql80-upgrade $(basename "$work") $phase] $*"
}

occ() {
    docker exec "$name" su -s /bin/sh -c "cd /home/appbox/public_html && php occ $*" appbox
}

# Runs one SQL statement as MySQL root inside the container; prints the rows.
sql() {
    docker exec -e "CYLO_SQL=$1" "$name" sh -c 'MYSQL_PWD="$DB_PASS" mysql -uroot -N -B -e "$CYLO_SQL"'
}

test_file_rows() {
    sql "SELECT COUNT(*) FROM nextcloud.nc_filecache WHERE path = 'files/mysql80-check.txt'"
}

server_version() {
    local attempt
    for attempt in $(seq 1 60); do
        sql 'SELECT VERSION()' 2>/dev/null && return 0
        sleep 2
    done
    return 1
}

case "$phase" in
nc-upgrade)
    before=$(server_version) || fail "cannot query MySQL"
    case "$before" in 8.0.*) ;; *) fail "the installation runs MySQL $before, not 8.0" ;; esac
    # shellcheck disable=SC2086
    docker exec -i "$name" bash -s -- $nc_path <<'IN'
set -euo pipefail
occ() { su -s /bin/sh -c "cd /home/appbox/public_html && php occ $*" appbox; }
base=https://download.nextcloud.com/server/releases
for version in "$@"; do
    rm -rf /tmp/nc-upgrade
    mkdir /tmp/nc-upgrade
    curl -fsSL "$base/nextcloud-$version.zip" -o /tmp/nc-upgrade/nextcloud.zip
    curl -fsSL "$base/nextcloud-$version.zip.sha256" -o /tmp/nc-upgrade/nextcloud.zip.sha256
    # The .sha256 file also lists other release files; use the zip's entry.
    expected=$(awk -v f="nextcloud-$version.zip" '$2 == f {print $1}' /tmp/nc-upgrade/nextcloud.zip.sha256)
    actual=$(sha256sum /tmp/nc-upgrade/nextcloud.zip | cut -d' ' -f1)
    if [ "$(printf '%s\n' "$expected" | grep -c .)" -ne 1 ] || [ "$expected" != "$actual" ]; then
        echo "nextcloud-$version.zip: SHA-256 $actual does not match the published '$expected'" >&2
        exit 1
    fi
    unzip -q /tmp/nc-upgrade/nextcloud.zip -d /tmp/nc-upgrade
    occ maintenance:mode --on
    find /home/appbox/public_html -mindepth 1 -maxdepth 1 ! -name config -exec rm -rf {} +
    cp -a /tmp/nc-upgrade/nextcloud/. /home/appbox/public_html/
    chown -R appbox:appbox /home/appbox/public_html
    occ --no-interaction upgrade
    occ maintenance:mode --off
    echo "Nextcloud now reports $(occ status --output=json | sed -n 's/.*"versionstring":"\([^"]*\)".*/\1/p')"
done
rm -rf /tmp/nc-upgrade
IN
    status_version=$(occ status --output=json | jq -r '.versionstring')
    [ "$status_version" = "$nc_final" ] || fail "Nextcloud reports $status_version after the upgrade, expected $nc_final"
    head -c 4096 /dev/urandom | od -An -tx1 | tr -d ' \n' > "$work/test-file"
    docker exec -i "$name" sh -c "mkdir -p /storage/$admin_user/files && cat > /storage/$admin_user/files/mysql80-check.txt && chown -R appbox:appbox /storage/$admin_user/files" < "$work/test-file"
    occ files:scan --path="$admin_user/files/mysql80-check.txt" >/dev/null
    [ "$(test_file_rows)" = 1 ] || fail "the test file is not in the file cache"
    dbuser=$(docker exec "$name" php -r 'include "/home/appbox/public_html/config/config.php"; echo $CONFIG["dbuser"];')
    plugin=$(sql "SELECT DISTINCT plugin FROM mysql.user WHERE user = '$dbuser'")
    [ "$plugin" = mysql_native_password ] \
        || fail "the Nextcloud database user $dbuser uses '$plugin'; the fixture needs mysql_native_password"
    "$recreate_test" "$work" rebaseline
    say "Nextcloud $status_version on MySQL $before; database user $dbuser uses mysql_native_password; test file added"
    ;;

kill)
    docker kill -s KILL "$name" >/dev/null
    say "container killed; MySQL 8.0 did not shut down"
    ;;

check-84)
    version=$(server_version) || fail "cannot query MySQL after the update"
    [ "$version" = 8.4.11 ] || fail "MySQL $version runs after the update, expected 8.4.11"
    backup=$vol/mysql_data/data.mysql80-backup
    [ -d "$backup" ] || fail "no copy of the MySQL 8.0 data directory in mysql_data/"
    grep -Eq '^8\.0\.' "$backup/mysql_upgrade_info" || fail "the copy is not a MySQL 8.0 data directory"
    [ ! -e "$vol/mysql_data/data.mysql80-backup.partial" ] || fail "an unfinished copy was left behind"
    say "MySQL $version; MySQL $(cat "$backup/mysql_upgrade_info") data copied to mysql_data/data.mysql80-backup"
    dbuser=$(docker exec "$name" php -r 'include "/home/appbox/public_html/config/config.php"; echo $CONFIG["dbuser"];')
    plugin=$(sql "SELECT DISTINCT plugin FROM mysql.user WHERE user = '$dbuser'")
    [ "$plugin" = mysql_native_password ] || fail "the database user $dbuser now uses '$plugin'"
    [ "$(occ status --output=json | jq -r '.installed')" = true ] || fail "Nextcloud cannot use its database"
    [ "$(test_file_rows)" = 1 ] || fail "the test file is missing from the file cache"
    cmp -s "$work/test-file" "$vol/user_data/$admin_user/files/mysql80-check.txt" || fail "the test file changed"
    occ setupchecks --output=json > "$work/setupchecks-84.json" || true
    for check in PhpOutdated SupportedDatabase FileLocking MemcacheConfigured; do
        severity=$(jq -r --arg c "OCA\\Settings\\SetupChecks\\$check" '[.[] | to_entries[] | select(.key == $c) | .value.severity][0] // "missing"' "$work/setupchecks-84.json")
        [ "$severity" = success ] || fail "setup check $check reports $severity"
    done
    docker exec "$name" sv status redis | grep -q '^run: redis' || fail "Redis is not running"
    say "database user $dbuser (mysql_native_password) works; PhpOutdated, SupportedDatabase, FileLocking and MemcacheConfigured pass; test file present"
    echo "MySQL errors and warnings logged since the update:"
    docker exec "$name" sh -c 'awk "/8\\.4\\.11/ {seen = 1} seen && /\\[(ERROR|Warning)\\]/" /home/appbox/logs/mysql/error.log | sed -E "s/^[^ ]+ //" | cut -c1-200 | sort | uniq -c | sort -rn | head -20' | sed 's/^/    /' || true
    ;;

rollback)
    for key in memcache.locking memcache.distributed redis; do
        occ config:system:delete "$key" >/dev/null
    done
    "$recreate_test" "$work" rebaseline
    docker stop -t 120 "$name" >/dev/null
    docker run --rm --network none -v "$vol/mysql_data:/m" --entrypoint bash "$image" -ec '
        test -d /m/data.mysql80-backup
        mv /m/data /m/data.mysql84
        mv /m/data.mysql80-backup /m/data'
    say "Redis entries removed, MySQL 8.0 copy put back; recreating from $image"
    "$recreate_test" "$work" recreate "$image"
    version=$(server_version) || fail "cannot query MySQL after going back"
    case "$version" in 8.0.*) ;; *) fail "MySQL $version runs after going back, expected 8.0" ;; esac
    [ "$(test_file_rows)" = 1 ] || fail "the test file is missing after going back"
    say "back on MySQL $version with Nextcloud $(occ status --output=json | jq -r '.versionstring'); test file present"
    ;;
esac
